/** A 5×7 caps-only font: uppercase, digits and ASCII punctuation. */
fun SZBitmapFont.Companion.pixel5x7(): SZBitmapFont = SZBitmapFont(
    name = "pixel5x7",
    glyphs = PIXEL_5X7_GLYPHS.map { (character, art) -> character to SZBitmap.parse(art.split('|')) },
    lineHeight = 9,
    caps = true,
)

/**
 * The 5×7 font with another font's glyphs for everything it lacks, such as
 * k8x12's kana and kanji. Both sit on one baseline in a cell as tall as the
 * taller of the two, so mixed text lines up.
 *
 * @param lowercase Adds 5×7 lowercase with descenders, which the cell's
 *   descent has room for; without it, lowercase maps to caps.
 */
fun SZBitmapFont.Companion.pixel5x7(fallback: SZGlyphSource, lowercase: Boolean = true): SZBitmapFont {
    // The 5×7 glyphs sit on the baseline below their seventh row.
    val baseAscent = 7
    val ascent = max(baseAscent, fallback.ascent)
    val height = ascent + max(fallback.descent, if (lowercase) 2 else 0)
    val pad = ascent - baseAscent
    val art = if (lowercase) PIXEL_5X7_GLYPHS + PIXEL_5X7_LOWERCASE else PIXEL_5X7_GLYPHS
    val glyphs = art.map { (character, rows) ->
        val bitmap = SZBitmap.parse(rows.split('|'))
        character to SZBitmap(bitmap.width, LongArray(pad + bitmap.height) { if (it < pad) 0L else bitmap.rows[it - pad] })
    }
    return SZBitmapFont(
        name = "pixel5x7+fallback",
        glyphs = glyphs,
        lineHeight = height + 2,
        caps = !lowercase,
        source = fallback,
        sourceTop = ascent - fallback.ascent,
    )
}

